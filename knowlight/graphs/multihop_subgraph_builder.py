def bfs_multihop_search(
    adj: Dict[int, List[int]],
    start_node: int,
    max_hops: int = 2,
    max_neighbors_per_hop: Optional[int] = 10,
    exclude_node: Optional[int] = None
) -> Tuple[Dict[int, List[int]], Set[int]]:
    """
    Performs Breadth-First Search (BFS) starting from `start_node` up to `max_hops`.
    
    Args:
        adj: Precomputed adjacency dictionary mapping node -> list of neighbors
        start_node: Int index of the starting center node
        max_hops: Maximum BFS exploration depth k (0, 1, ..., k)
        max_neighbors_per_hop: Maximum number of neighbors to sample per node at each hop
        
    Returns:
        hop_nodes: Dict mapping hop_level (0, 1, ..., max_hops) -> list of node IDs at that hop
        visited: Set of all node IDs visited in the multi-hop subgraph
    """
    visited: Set[int] = {start_node}
    if exclude_node is not None:
        visited.add(exclude_node)
        
    queue = deque([(start_node, 0)])

    hop_nodes: Dict[int, List[int]] = {h: [] for h in range(max_hops + 1)}
    hop_nodes[0] = [start_node]

    while queue:
        current_node, current_hop = queue.popleft()

        if current_hop >= max_hops:
            continue

        neighbors = adj.get(current_node, [])
        if max_neighbors_per_hop is not None and len(neighbors) > max_neighbors_per_hop:
            neighbors = neighbors[:max_neighbors_per_hop]

        for neighbor in neighbors:
            if neighbor not in visited:
                visited.add(neighbor)
                next_hop = current_hop + 1
                hop_nodes[next_hop].append(neighbor)
                queue.append((neighbor, next_hop))

    return hop_nodes, visited


class MultiHopSubgraphBuilder:
    """
    Extracts multi-hop subgraphs G_i^{(l)} and textual attributes using BFS.
    """

    def __init__(self, pyg_graph: Any, edge_mask: Optional[torch.Tensor] = None):
        """
        Args:
            pyg_graph: PyG Data object generated by TAGGraphBuilder.
            edge_mask: Boolean tensor of shape [num_edges] to filter edges (e.g., train_edge_mask).
        """
        object.__setattr__(pyg_graph, "_store", pyg_graph.__dict__)
        self.graph = pyg_graph
        self.edge_index = pyg_graph.edge_index
        self.raw_text = getattr(pyg_graph, "raw_text", getattr(pyg_graph, "node_text", []))
        self.user_mapping = getattr(pyg_graph, "user_mapping", {})
        self.item_mapping = getattr(pyg_graph, "item_mapping", {})
        self.num_users = getattr(pyg_graph, "num_users", 0)
        self.num_items = getattr(pyg_graph, "num_items", 0)

        # Precompute adjacency list once to avoid O(|E|) operations on every subgraph query
        self.adj_list: Dict[int, List[int]] = {}
        src, dst = self.edge_index[0].tolist(), self.edge_index[1].tolist()
        
        if edge_mask is not None:
            mask_list = edge_mask.tolist()
            for u, v, m in zip(src, dst, mask_list):
                if m:
                    if u not in self.adj_list:
                        self.adj_list[u] = []
                    self.adj_list[u].append(v)
        else:
            for u, v in zip(src, dst):
                if u not in self.adj_list:
                    self.adj_list[u] = []
                self.adj_list[u].append(v)

    def get_subgraph_context(
        self,
        node_id: int,
        max_hops: int = 2,
        max_neighbors_per_hop: int = 10,
        exclude_node_id: Optional[int] = None
    ) -> Dict[str, Any]:
        """
        Extracts multi-hop subgraph G_i^{(l)} for node_id via BFS.
        
        Returns:
            Dict containing:
            - center_node: node ID
            - hop_nodes: Dict of nodes at hop 0, hop 1, ..., hop k
            - hop_attributes: Dict of raw text strings at hop 0, 1, ..., k
            - subgraph_edge_index: PyG edge_index for the induced multi-hop subgraph G_i^{(l)}
        """
        hop_nodes, visited_set = bfs_multihop_search(
            adj=self.adj_list,
            start_node=node_id,
            max_hops=max_hops,
            max_neighbors_per_hop=max_neighbors_per_hop,
            exclude_node=exclude_node_id
        )

        # Collect raw textual attributes at each hop
        hop_attributes: Dict[int, List[str]] = {}
        for h, nodes in hop_nodes.items():
            attr_list = []
            for n in nodes:
                text = self.raw_text[n] if (self.raw_text and n < len(self.raw_text)) else f"Node_{n}"
                attr_list.append(text)
            hop_attributes[h] = attr_list

        # Extract induced subgraph edges G_i^{(l)} efficiently using precomputed adjacency
        subgraph_src = []
        subgraph_dst = []
        for u in visited_set:
            if u in self.adj_list:
                for v in self.adj_list[u]:
                    if v in visited_set:
                        subgraph_src.append(u)
                        subgraph_dst.append(v)
                        
        if subgraph_src:
            subgraph_edge_index = torch.tensor([subgraph_src, subgraph_dst], dtype=torch.long)
        else:
            subgraph_edge_index = torch.empty((2, 0), dtype=torch.long)

        return {
            "center_node": node_id,
            "center_text": self.raw_text[node_id] if (self.raw_text and node_id < len(self.raw_text)) else f"Node_{node_id}",
            "max_hops": max_hops,
            "hop_nodes": hop_nodes,
            "hop_attributes": hop_attributes,
            "num_subgraph_nodes": len(visited_set),
            "num_subgraph_edges": int(subgraph_edge_index.shape[1]),
            "subgraph_edge_index": subgraph_edge_index
        }

    def get_item_subgraph_context_by_raw_id(self, item_raw_id: str, max_hops: int = 2, max_neighbors_per_hop: int = 10) -> Dict[str, Any]:
        """Convenience method to query an item by its raw string ID (e.g. ASIN / MovieID)."""
        node_id = self.item_mapping[str(item_raw_id)]
        return self.get_subgraph_context(node_id, max_hops=max_hops, max_neighbors_per_hop=max_neighbors_per_hop)

    def get_user_subgraph_context_by_raw_id(self, user_raw_id: str, max_hops: int = 2, max_neighbors_per_hop: int = 10, exclude_item_raw_id: Optional[str] = None) -> Dict[str, Any]:
        """Convenience method to query a user by their raw string ID."""
        node_id = self.user_mapping[str(user_raw_id)]
        exclude_node_id = self.item_mapping[str(exclude_item_raw_id)] if exclude_item_raw_id is not None and str(exclude_item_raw_id) in self.item_mapping else None
        return self.get_subgraph_context(node_id, max_hops=max_hops, max_neighbors_per_hop=max_neighbors_per_hop, exclude_node_id=exclude_node_id)


def process_dataset_multihop_subgraphs(
    dataset_name: str,
    max_hops: int = 2,
    max_neighbors_per_hop: int = 10,
    graph_dir: Path = root_dir / "graphs" / "output"
) -> Dict[str, Any]:
    """Loads dataset PyG graph and extracts multi-hop subgraphs for sample users and items."""
    graph_path = graph_dir / f"{dataset_name}_tag_graph.pt"
    if not graph_path.exists():
        raise FileNotFoundError(f"PyG graph file not found: {graph_path}. Please run `python graphs/generate_tag_graphs.py --dataset {dataset_name}` first.")

    logging.info(f"Loading PyG TAG graph for '{dataset_name}' from {graph_path}...")
    pyg_graph = torch.load(graph_path, weights_only=False)

    builder = MultiHopSubgraphBuilder(pyg_graph)

    # Sample first item and first user
    sample_item_raw = list(builder.item_mapping.keys())[0] if builder.item_mapping else None
    sample_user_raw = list(builder.user_mapping.keys())[0] if builder.user_mapping else None

    results = {"dataset_name": dataset_name, "max_hops": max_hops, "sample_item_subgraph": None, "sample_user_subgraph": None}

    if sample_item_raw:
        item_ctx = builder.get_item_subgraph_context_by_raw_id(sample_item_raw, max_hops=max_hops, max_neighbors_per_hop=max_neighbors_per_hop)
        results["sample_item_subgraph"] = {
            "item_id": sample_item_raw,
            "center_text": item_ctx["center_text"],
            "num_subgraph_nodes": item_ctx["num_subgraph_nodes"],
            "num_subgraph_edges": item_ctx["num_subgraph_edges"],
            "hop_0_text": item_ctx["hop_attributes"].get(0, []),
            "hop_1_sample_texts": item_ctx["hop_attributes"].get(1, [])[:3],
            "hop_2_sample_texts": item_ctx["hop_attributes"].get(2, [])[:3],
        }

    if sample_user_raw:
        user_ctx = builder.get_user_subgraph_context_by_raw_id(sample_user_raw, max_hops=max_hops, max_neighbors_per_hop=max_neighbors_per_hop)
        results["sample_user_subgraph"] = {
            "user_id": sample_user_raw,
            "center_text": user_ctx["center_text"],
            "num_subgraph_nodes": user_ctx["num_subgraph_nodes"],
            "num_subgraph_edges": user_ctx["num_subgraph_edges"],
            "hop_0_text": user_ctx["hop_attributes"].get(0, []),
            "hop_1_sample_texts": user_ctx["hop_attributes"].get(1, [])[:3],
            "hop_2_sample_texts": user_ctx["hop_attributes"].get(2, [])[:3],
        }

    return results
